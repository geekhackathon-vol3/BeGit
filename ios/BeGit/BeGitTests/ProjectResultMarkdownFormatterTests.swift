import XCTest
@testable import BeGit

final class ProjectResultMarkdownFormatterTests: XCTestCase {
    func testMarkdownContainsFinalResultAndSortsMembersByTotalPoints() {
        let result = ProjectFinalResult(
            groupID: 1,
            completedAt: "2026-10-25 15:50:36",
            members: [
                ProjectMemberPoints(
                    userID: 2, login: "たくみ", avatarURL: "",
                    reportPoints: 270, bonusPoints: 10, totalPoints: 280
                ),
                ProjectMemberPoints(
                    userID: 1, login: "あやか", avatarURL: "",
                    reportPoints: 300, bonusPoints: 20, totalPoints: 320
                )
            ],
            teamTotal: 1_280,
            modeResults: []
        )

        let markdown = ProjectResultMarkdownFormatter().makeMarkdown(
            repositoryName: "ハッカソン/BeGit",
            result: result
        )

        XCTAssertEqual(markdown, """
        # 🏆 Hackathon Result

        ## チーム
        ハッカソン/BeGit

        ## 完成日時
        2026-10-26 00:50 GMT+9

        ## チーム合計
        **1,280 pt**

        ## メンバー別ポイント
        - 🥇 **@あやか** 320 pt（報告 300 pt / ボーナス 20 pt）
        - 🥈 **@たくみ** 280 pt（報告 270 pt / ボーナス 10 pt）

        Generated by BeGit

        """)
    }

    func testMarkdownDoesNotUseTablesForChatApps() {
        let result = ProjectFinalResult(
            groupID: 1,
            completedAt: "2026-10-25 15:50:36",
            members: [
                ProjectMemberPoints(userID: 1, login: "alice", avatarURL: "", reportPoints: 10, bonusPoints: 0, totalPoints: 10)
            ],
            teamTotal: 10,
            modeResults: [
                ProjectModeResult(gameMode: .everyone, attempts: 1, successes: 1, failures: 0, cancelled: 0, bonusPoints: 5)
            ]
        )

        let markdown = ProjectResultMarkdownFormatter().makeMarkdown(repositoryName: "BeGit", result: result)

        XCTAssertFalse(markdown.contains("|---"))
        XCTAssertFalse(markdown.contains("| "))
    }

    func testMarkdownEscapesMarkdownSymbolsAndUsesStableTieBreak() {
        let result = ProjectFinalResult(
            groupID: 1,
            completedAt: "2026-10-26T00:50:36+09:00",
            members: [
                ProjectMemberPoints(
                    userID: 2, login: "b_user", avatarURL: "",
                    reportPoints: 10, bonusPoints: 0, totalPoints: 10
                ),
                ProjectMemberPoints(
                    userID: 1, login: "a\nuser", avatarURL: "",
                    reportPoints: 10, bonusPoints: 0, totalPoints: 10
                )
            ],
            teamTotal: 20,
            modeResults: []
        )

        let markdown = ProjectResultMarkdownFormatter().makeMarkdown(
            repositoryName: "日本語\n*Repository*",
            result: result
        )

        XCTAssertTrue(markdown.contains("日本語 \\*Repository\\*"))
        XCTAssertTrue(markdown.contains("""
        - 🥇 **@a user** 10 pt（報告 10 pt / ボーナス 0 pt）
        - 🥇 **@b\\_user** 10 pt（報告 10 pt / ボーナス 0 pt）
        """))
    }

    func testMarkdownContainsGameResultsAndRanksWithTies() {
        let result = ProjectFinalResult(
            groupID: 1,
            completedAt: "2026-10-25 15:50:36",
            members: [
                ProjectMemberPoints(userID: 1, login: "alice", avatarURL: "", reportPoints: 100, bonusPoints: 0, totalPoints: 100),
                ProjectMemberPoints(userID: 2, login: "bob", avatarURL: "", reportPoints: 100, bonusPoints: 0, totalPoints: 100),
                ProjectMemberPoints(userID: 3, login: "carol", avatarURL: "", reportPoints: 50, bonusPoints: 0, totalPoints: 50),
                ProjectMemberPoints(userID: 4, login: "dave", avatarURL: "", reportPoints: 40, bonusPoints: 0, totalPoints: 40),
                ProjectMemberPoints(userID: 5, login: "eve", avatarURL: "", reportPoints: 10, bonusPoints: 0, totalPoints: 10)
            ],
            teamTotal: 300,
            modeResults: [
                ProjectModeResult(gameMode: .everyone, attempts: 5, successes: 3, failures: 1, cancelled: 1, pending: 0, bonusPoints: 1_500),
                ProjectModeResult(gameMode: .spotlight, attempts: 2, successes: 1, failures: 0, cancelled: 0, pending: 1, bonusPoints: 20)
            ]
        )

        let markdown = ProjectResultMarkdownFormatter().makeMarkdown(repositoryName: "BeGit", result: result)

        XCTAssertTrue(markdown.contains("""
        - 🥇 **@alice** 100 pt（報告 100 pt / ボーナス 0 pt）
        - 🥇 **@bob** 100 pt（報告 100 pt / ボーナス 0 pt）
        - 🥉 **@carol** 50 pt（報告 50 pt / ボーナス 0 pt）
        - 4位 **@dave** 40 pt（報告 40 pt / ボーナス 0 pt）
        - 5位 **@eve** 10 pt（報告 10 pt / ボーナス 0 pt）
        """))
        XCTAssertTrue(markdown.contains("""
        ## ゲームリザルト
        - **みんな、今何作ってる？** 達成 3/5・失敗 1・途中終了 1・判定中 0・ボーナス +1,500 pt
        - **俺の進捗を見ろ！** 達成 1/2・失敗 0・途中終了 0・判定中 1・ボーナス +20 pt
        """))
    }

    func testMarkdownForInterimSummaryIsMarkedAsInProgress() {
        let summary = ProjectPointsSummary(
            groupID: 1,
            isFinal: false,
            completedAt: nil,
            members: [
                ProjectMemberPoints(userID: 1, login: "alice", avatarURL: "", reportPoints: 30, bonusPoints: 0, totalPoints: 30)
            ],
            teamTotal: 30,
            modeResults: []
        )

        let markdown = ProjectResultMarkdownFormatter().makeMarkdown(repositoryName: "BeGit", summary: summary)

        XCTAssertTrue(markdown.hasPrefix("# 🏆 Hackathon Result（集計中）\n> ⏳ 集計中の暫定リザルトです\n"))
        XCTAssertFalse(markdown.contains("## 完成日時"))
        XCTAssertFalse(markdown.contains("## ゲームリザルト"))
        XCTAssertTrue(markdown.contains("- 🥇 **@alice** 30 pt（報告 30 pt / ボーナス 0 pt）"))
    }
}

import Foundation

struct ProjectResultMarkdownFormatter {
    private let timeZone: TimeZone

    init(timeZone: TimeZone = TimeZone(identifier: "Asia/Tokyo")!) {
        self.timeZone = timeZone
    }

    func makeMarkdown(repositoryName: String, result: ProjectFinalResult) -> String {
        let members = result.members.sorted {
            if $0.totalPoints != $1.totalPoints {
                return $0.totalPoints > $1.totalPoints
            }
            let lhs = $0.login.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
            let rhs = $1.login.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
            return lhs == rhs ? $0.login < $1.login : lhs < rhs
        }

        var lines = [
            "# Hackathon Result",
            "",
            "## チーム",
            "",
            sanitizedParagraph(repositoryName),
            "",
            "## 完成日時",
            "",
            completionDateText(result.completedAt),
            "",
            "## チーム合計",
            "",
            "\(formattedPoints(result.teamTotal)) pt",
            "",
            "## メンバー別ポイント",
            "",
            "| メンバー | 報告ポイント | ボーナスポイント | 合計 |",
            "|---|---:|---:|---:|"
        ]

        lines.append(contentsOf: members.map { member in
            "| @\(escapedTableCell(member.login)) | \(formattedPoints(member.reportPoints)) pt | \(formattedPoints(member.bonusPoints)) pt | \(formattedPoints(member.totalPoints)) pt |"
        })
        lines.append(contentsOf: ["", "Generated by BeGit", ""])
        return lines.joined(separator: "\n")
    }

    private func formattedPoints(_ value: Int) -> String {
        let formatter = NumberFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.numberStyle = .decimal
        formatter.maximumFractionDigits = 0
        formatter.usesGroupingSeparator = true
        formatter.groupingSize = 3
        formatter.groupingSeparator = ","
        return formatter.string(from: NSNumber(value: value)) ?? String(value)
    }

    func completionDateText(_ value: String) -> String {
        guard let date = parseDate(value) else { return sanitizedParagraph(value) }
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = timeZone
        formatter.dateFormat = "yyyy-MM-dd HH:mm zzz"
        return formatter.string(from: date)
    }

    private func parseDate(_ value: String) -> Date? {
        let iso8601 = ISO8601DateFormatter()
        iso8601.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        if let date = iso8601.date(from: value) { return date }
        iso8601.formatOptions = [.withInternetDateTime]
        if let date = iso8601.date(from: value) { return date }

        let sqlite = DateFormatter()
        sqlite.locale = Locale(identifier: "en_US_POSIX")
        sqlite.calendar = Calendar(identifier: .gregorian)
        sqlite.timeZone = TimeZone(secondsFromGMT: 0)
        sqlite.dateFormat = "yyyy-MM-dd HH:mm:ss"
        return sqlite.date(from: value)
    }

    private func sanitizedParagraph(_ value: String) -> String {
        value.replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
    }

    private func escapedTableCell(_ value: String) -> String {
        sanitizedParagraph(value)
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "|", with: "\\|")
    }
}

import Foundation

struct ProjectResultMarkdownFormatter {
    struct RankedMember: Identifiable {
        let rank: Int
        let member: ProjectMemberPoints

        var id: Int64 { member.id }
    }

    private let timeZone: TimeZone

    init(timeZone: TimeZone = TimeZone(identifier: "Asia/Tokyo")!) {
        self.timeZone = timeZone
    }

    /// 最終結果（確定済み）のMarkdownを生成する
    func makeMarkdown(repositoryName: String, result: ProjectFinalResult) -> String {
        makeMarkdown(repositoryName: repositoryName, summary: ProjectPointsSummary(finalResult: result))
    }

    /// ポイント集計（確定前の暫定結果も含む）のMarkdownを生成する。
    /// Discord / Slack は表（テーブル）記法に対応していないため、見出しと箇条書きだけで構成する。
    func makeMarkdown(repositoryName: String, summary: ProjectPointsSummary) -> String {
        let isFinal = summary.finalResult != nil

        var lines = [
            isFinal ? "# 🏆 Hackathon Result" : "# 🏆 Hackathon Result（集計中）"
        ]
        if isFinal == false {
            lines.append("> ⏳ 集計中の暫定リザルトです")
        }

        lines.append(contentsOf: [
            "",
            "## チーム",
            escapedInline(repositoryName)
        ])

        if isFinal, let completedAt = summary.completedAt {
            lines.append(contentsOf: [
                "",
                "## 完成日時",
                completionDateText(completedAt)
            ])
        }

        lines.append(contentsOf: [
            "",
            "## チーム合計",
            "**\(formattedPoints(summary.teamTotal)) pt**",
            "",
            "## メンバー別ポイント"
        ])
        lines.append(contentsOf: rankedMembers(summary.members).map { (ranked: RankedMember) -> String in
            let member = ranked.member
            return "- \(rankLabel(ranked.rank)) **@\(escapedInline(member.login))** \(formattedPoints(member.totalPoints)) pt"
                + "（報告 \(formattedPoints(member.reportPoints)) pt / ボーナス \(formattedPoints(member.bonusPoints)) pt）"
        })

        if summary.modeResults.isEmpty == false {
            lines.append(contentsOf: [
                "",
                "## ゲームリザルト"
            ])
            lines.append(contentsOf: summary.modeResults.map { (mode: ProjectModeResult) -> String in
                "- **\(escapedInline(mode.gameMode.title))** 達成 \(mode.successes)/\(mode.attempts)"
                    + "・失敗 \(mode.failures)・途中終了 \(mode.cancelled)・判定中 \(mode.pending)"
                    + "・ボーナス +\(formattedPoints(mode.bonusPoints)) pt"
            })
        }

        lines.append(contentsOf: ["", "Generated by BeGit", ""])
        return lines.joined(separator: "\n")
    }

    /// 合計ポイント降順（同点はlogin順）に並べ、同点は同順位として順位を付ける
    func rankedMembers(_ members: [ProjectMemberPoints]) -> [RankedMember] {
        let sorted = members.sorted {
            if $0.totalPoints != $1.totalPoints {
                return $0.totalPoints > $1.totalPoints
            }
            let lhs = $0.login.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
            let rhs = $1.login.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: Locale(identifier: "en_US_POSIX"))
            return lhs == rhs ? $0.login < $1.login : lhs < rhs
        }

        var ranked: [RankedMember] = []
        for (index, member) in sorted.enumerated() {
            if let previous = ranked.last, previous.member.totalPoints == member.totalPoints {
                ranked.append(RankedMember(rank: previous.rank, member: member))
            } else {
                ranked.append(RankedMember(rank: index + 1, member: member))
            }
        }
        return ranked
    }

    private func rankLabel(_ rank: Int) -> String {
        switch rank {
        case 1: "🥇"
        case 2: "🥈"
        case 3: "🥉"
        default: "\(rank)位"
        }
    }

    private func formattedPoints(_ value: Int) -> String {
        let formatter = NumberFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.numberStyle = .decimal
        formatter.maximumFractionDigits = 0
        formatter.usesGroupingSeparator = true
        formatter.groupingSize = 3
        formatter.groupingSeparator = ","
        return formatter.string(from: NSNumber(value: value)) ?? String(value)
    }

    func completionDateText(_ value: String) -> String {
        guard let date = parseDate(value) else { return sanitizedParagraph(value) }
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = timeZone
        formatter.dateFormat = "yyyy-MM-dd HH:mm zzz"
        return formatter.string(from: date)
    }

    private func parseDate(_ value: String) -> Date? {
        let iso8601 = ISO8601DateFormatter()
        iso8601.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        if let date = iso8601.date(from: value) { return date }
        iso8601.formatOptions = [.withInternetDateTime]
        if let date = iso8601.date(from: value) { return date }

        let sqlite = DateFormatter()
        sqlite.locale = Locale(identifier: "en_US_POSIX")
        sqlite.calendar = Calendar(identifier: .gregorian)
        sqlite.timeZone = TimeZone(secondsFromGMT: 0)
        sqlite.dateFormat = "yyyy-MM-dd HH:mm:ss"
        return sqlite.date(from: value)
    }

    private func sanitizedParagraph(_ value: String) -> String {
        value.replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
    }

    /// Markdown記法として解釈される記号をエスケープする
    private func escapedInline(_ value: String) -> String {
        var escaped = sanitizedParagraph(value).replacingOccurrences(of: "\\", with: "\\\\")
        for symbol in ["*", "_", "~", "`", "|", "#", ">", "["] {
            escaped = escaped.replacingOccurrences(of: symbol, with: "\\" + symbol)
        }
        return escaped
    }
}
